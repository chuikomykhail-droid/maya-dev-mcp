# Captures the environment that vcvars64.bat sets up and writes it as a hidden CMake configure preset
# (plugins/cmake/msvc-env.json, included by CMakePresets.json). This way both the terminal and VS Code
# CMake Tools build with MSVC without a Developer Prompt and without vswhere.
# Re-run after a Visual Studio / MSVC / Windows SDK update:  tools\build.cmd relwithdebinfo env
param(
    [string]$VcVars = $(if ($env:MAYA_PLUGINS_VCVARS) { $env:MAYA_PLUGINS_VCVARS } else { 'D:\Soft\Visual Studio\VC\Auxiliary\Build\vcvars64.bat' }),
    [string]$OutFile = (Join-Path $PSScriptRoot '..\cmake\msvc-env.json')
)
$ErrorActionPreference = 'Stop'

if (-not (Test-Path -LiteralPath $VcVars)) {
    throw "vcvars64.bat not found: $VcVars (pass -VcVars or set MAYA_PLUGINS_VCVARS)"
}

function Read-Env([string[]]$lines) {
    $vars = @{}
    foreach ($line in $lines) {
        if ($line -match '^([^=]+)=(.*)$') { $vars[$Matches[1]] = $Matches[2] }
    }
    $vars
}

$before = Read-Env (cmd /d /c set)
$after = Read-Env (cmd /d /c "`"$VcVars`" >nul 2>&1 && set")
if ($LASTEXITCODE -ne 0 -or -not $after['INCLUDE']) {
    throw "vcvars64.bat failed (exit code $LASTEXITCODE): $VcVars"
}

$environment = [ordered]@{}
foreach ($name in ($after.Keys | Sort-Object)) {
    if ($name -in 'PATH', 'PROMPT' -or $name.StartsWith('__')) { continue }
    if ($before[$name] -ne $after[$name]) { $environment[$name] = $after[$name] }
}

# Keep only the PATH entries vcvars added; the rest comes from the parent process at build time.
$oldPath = @($before['PATH'] -split ';' | Where-Object { $_ })
$added = @($after['PATH'] -split ';' | Where-Object { $_ -and $oldPath -notcontains $_ } | Select-Object -Unique)
$environment['PATH'] = ($added -join ';') + ';$penv{PATH}'

$preset = [ordered]@{
    version = 6
    configurePresets = @(
        [ordered]@{
            name = 'msvc-env'
            hidden = $true
            description = "Generated by tools/gen-msvc-env.ps1 from $VcVars"
            environment = $environment
        }
    )
}

$json = $preset | ConvertTo-Json -Depth 6
[System.IO.File]::WriteAllText([System.IO.Path]::GetFullPath($OutFile), $json, (New-Object System.Text.UTF8Encoding $false))
Write-Host "MSVC environment ($($after['VCToolsVersion']), SDK $($after['WindowsSDKVersion'].TrimEnd('\'))) written to $([System.IO.Path]::GetFullPath($OutFile))"
